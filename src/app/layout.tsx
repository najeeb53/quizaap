import type { Metadata } from "next";
import { Geist, Geist_Mono } from "next/font/google";
import "./globals.css";

const geistSans = Geist({
  variable: "--font-geist-sans",
  subsets: ["latin"],
});

const geistMono = Geist_Mono({
  variable: "--font-geist-mono",
  subsets: ["latin"],
});

export const metadata: Metadata = {
  title: "Live Quiz Show",
  description: "Live quiz host, team and projector screens.",
};

// Typed explicitly rather than with Next's generated `LayoutProps` global, which only exists once a
// build has written .next/types — so a plain `tsc --noEmit` (the only way to see type errors at all
// while next.config.ts has ignoreBuildErrors on) flagged it as an unknown name.
export default function RootLayout({ children }: { children: React.ReactNode }) {
  return (
    <html
      lang="en"
      className={`${geistSans.variable} ${geistMono.variable} h-full antialiased`}
    >
      <body className="min-h-full flex flex-col" suppressHydrationWarning>{children}</body>
    </html>
  );
}
